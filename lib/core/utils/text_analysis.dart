/// 한국어 동사/형용사 어미를 제거하여 어근을 추출합니다.
/// 긴 어미부터 매칭하여 가장 정확한 어근을 반환합니다.
String stemKorean(String word) {
  // 긴 어미부터 시도 (greedy matching)
  const suffixes = [
    // 4음절 어미
    '스러웠다', '스러운',
    // 3음절 어미
    '했는데', '었는데', '았는데', '였는데',
    '했지만', '었지만', '았지만', '였지만',
    '했으며', '었으며', '았으며',
    '하면서', '으면서', '되면서',
    '합니다', '됩니다', '입니다',
    '할까요', '될까요',
    '해줬다', '해봤다', '해왔다',
    '었었다', '았었다',
    '스럽다', '스러운', '스럽게',
    '답게', '롭게', '롭다',
    '했어요', '었어요', '았어요', '였어요',
    // 2음절 어미
    '했다', '었다', '았다', '였다', '됐다',
    '했고', '었고', '았고', '였고',
    '했어', '었어', '았어', '였어',
    '해서', '어서', '아서',
    '하고', '되고',
    '하며', '되며', '으며',
    '하면', '되면', '으면',
    '하는', '되는',
    '하게', '되게', '있게',
    '하지', '되지', '있지',
    '하다', '되다', '이다',
    '인데', '는데', '은데',
    '지만', '해도', '라도',
    '할수', '될수',
    '적인', '적으로',
    // 1음절 어미 (주의: 어근이 2자 이상일 때만)
    '한', '된', '할', '될', '함', '됨',
  ];

  for (final suffix in suffixes) {
    if (word.endsWith(suffix)) {
      final stem = word.substring(0, word.length - suffix.length);
      if (stem.length >= 2) return stem;
    }
  }

  return word;
}

/// 한국어 조사를 분리하여 명사 부분을 추출합니다.
String stripParticle(String word) {
  // 긴 조사부터 시도
  const particles = [
    '에게서', '한테서', '으로서', '으로써', '이라도', '이든지',
    '에서는', '에서도', '까지는', '까지도', '부터는', '만큼은',
    '에게', '한테', '으로', '에서', '까지', '부터', '만큼',
    '처럼', '마다', '밖에', '라도', '이라', '대로', '이랑',
    '이며', '에는', '에도', '과는', '와는',
    '은', '는', '이', '가', '을', '를', '의', '에',
    '로', '와', '과', '도', '만', '며', '랑', '야',
  ];

  for (final p in particles) {
    if (word.endsWith(p) && word.length > p.length) {
      final noun = word.substring(0, word.length - p.length);
      if (noun.length >= 2) return noun;
    }
  }
  return word;
}

final _nonWordRegex = RegExp(r'[^\w\s가-힣]');
final _whitespaceRegex = RegExp(r'\s+');

Map<String, int> extractKeywords(List<String> texts, {int limit = 10}) {
  final frequency = <String, int>{};

  for (final text in texts) {
    if (text.trim().isEmpty) continue;

    final words = text
        .replaceAll(_nonWordRegex, ' ')
        .split(_whitespaceRegex)
        .where((w) => w.length > 1)
        .where((w) => !koreanStopWords.contains(w))
        .map(stemKorean)
        .map(stripParticle)
        .where((w) => w.length > 1)
        .where((w) => !koreanStopWords.contains(w));

    for (final word in words) {
      frequency[word] = (frequency[word] ?? 0) + 1;
    }
  }

  final sorted = frequency.entries.toList()
    ..sort((a, b) => b.value.compareTo(a.value));

  return Map.fromEntries(sorted.take(limit));
}
