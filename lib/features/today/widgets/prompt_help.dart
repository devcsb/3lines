PromptCategory? categoryForQuestion(String question) {
  if (gratitudePromptPool.contains(question)) return PromptCategory.gratitude;
  if (acceptancePromptPool.contains(question)) return PromptCategory.acceptance;
  if (intentionPromptPool.contains(question)) return PromptCategory.intention;
  return null;
}

